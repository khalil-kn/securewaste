"""ML regression tests (SCRUM-46 M3). All documents are fictional.

These lock in current behaviour so a retrained model or a rule change cannot silently make things worse.
Accuracy floors are regression gates for these small fictional sets, not claims of production accuracy
(see docs/ml-evaluation-report.md, generated by `python -m scripts.evaluate_ml`).
"""

from pathlib import Path

import pytest

from scripts.evaluate_ml import MODELS, datasets, evaluate, render_report
from securewaste.core import ml_classifier
from securewaste.core.classifier import ClassificationLabel
from securewaste.core.extraction import PageText
from securewaste.core.ml_classifier import (
    REVIEW_THRESHOLD,
    ClassifierSource,
    MLClassificationResult,
    predict_classification_v3_dict,
)
from securewaste.core.risk import assess
from securewaste.services.detect_service import detect_pages

DATASET = Path("tests/fixtures/synthetic_dataset")
AWS_KEY = "AWS access key ID: AKIAQWERTYUIOPASDFGH."  # fictional, from scripts/evaluate_realistic.py
HMAC_KEY = b"test-only-hmac-key"


@pytest.fixture(autouse=True)
def baseline_model(monkeypatch):
    """Every test uses the committed baseline model unless it sets SECUREWASTE_MODEL_PATH itself."""
    monkeypatch.delenv("SECUREWASTE_MODEL_PATH", raising=False)


def fake_ml(monkeypatch, label, confidence):
    """Make the ML model answer `label` with `confidence`; the rules still run for real."""
    result = MLClassificationResult(ClassificationLabel(label), confidence, {}, ClassifierSource.ML)
    monkeypatch.setattr(ml_classifier, "predict_classification_with_confidence", lambda *_a, **_k: result)


# --- data hygiene ----------------------------------------------------------------------------


def test_no_document_text_is_shared_between_splits():
    def texts(split):
        return {p.read_text(encoding="utf-8").strip() for p in (DATASET / split).glob("*.txt")}

    train, val, test = texts("train"), texts("val"), texts("test")
    assert train and val and test
    assert not train & val and not train & test and not val & test


# --- the four labels -------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("text", "label"),
    [
        ("Welcome to our website. Learn more about our products and services.", "Public"),
        ("The engineering team will review sprint progress on Thursday.", "Internal"),
        ("Employee salary review: the proposed annual compensation is 92000 dollars.", "Confidential"),
        (AWS_KEY, "Highly Confidential"),
    ],
)
def test_every_label_is_reachable(text, label):
    assert predict_classification_v3_dict(text)["label"] == label


@pytest.mark.parametrize("model", list(MODELS))
def test_hybrid_never_underclassifies_the_evaluation_sets(model):
    for name, (texts, labels) in datasets().items():
        result = evaluate(model, MODELS[model], name, texts, labels, "hybrid")
        assert result.under == 0, f"{model} under-classified documents in {name}"


@pytest.mark.parametrize(("dataset", "floor"), [("synthetic test split", 0.90), ("realistic cases", 0.85)])
def test_baseline_hybrid_accuracy_does_not_regress(dataset, floor):
    texts, labels = datasets()[dataset]
    assert evaluate("baseline-v1", MODELS["baseline-v1"], dataset, texts, labels, "hybrid").accuracy >= floor


# --- model unavailable -----------------------------------------------------------------------


def _write_empty(path):
    path.write_bytes(b"")


def _write_garbage(path):
    path.write_bytes(b"not a pickle at all")


def _write_truncated(path):
    path.write_bytes(MODELS["baseline-v1"].read_bytes()[:200])


@pytest.mark.parametrize("broken", [None, _write_empty, _write_garbage, _write_truncated])
def test_missing_or_broken_model_falls_back_to_rules(tmp_path, monkeypatch, broken):
    model = tmp_path / "model.pkl"
    if broken is not None:
        broken(model)
    monkeypatch.setenv("SECUREWASTE_MODEL_PATH", str(model))

    result = predict_classification_v3_dict(AWS_KEY)
    assert result["label"] == "Highly Confidential"  # rules still catch the secret
    assert result["ml_label"] is None and result["ml_confidence"] is None
    assert result["requires_review"] is True

    harmless = predict_classification_v3_dict("The museum opens at nine.")
    assert harmless["decision_source"] == "rule_based"
    assert harmless["review_reason"] == "ML model unavailable; rule-based fallback"


# --- weak confidence and rule/ML disagreement ------------------------------------------------


@pytest.mark.parametrize(
    ("confidence", "review"), [(0.30, True), (REVIEW_THRESHOLD - 0.01, True), (REVIEW_THRESHOLD, False)]
)
def test_weak_ml_confidence_requires_review(monkeypatch, confidence, review):
    fake_ml(monkeypatch, "Internal", confidence)
    result = predict_classification_v3_dict("Please update the project board before Friday.")
    assert result["decision_source"] == "ml"
    assert result["requires_review"] is review
    assert (result["review_reason"] == "Low ML confidence") is review


def test_rules_override_a_confident_but_wrong_model(monkeypatch):
    fake_ml(monkeypatch, "Public", 0.97)
    result = predict_classification_v3_dict(AWS_KEY)
    assert result["label"] == "Highly Confidential"
    assert result["decision_source"] == "rule_override" and result["rule_override"] is True
    assert result["ml_label"] == "Public"  # the original disagreement stays visible to the reviewer
    assert result["requires_review"] is True and result["review_reason"] == "Sensitive-content rule override"


def test_rules_never_lower_the_model_label(monkeypatch):
    fake_ml(monkeypatch, "Highly Confidential", 0.9)
    result = predict_classification_v3_dict("The museum opens at nine and closes at six.")
    assert result["label"] == "Highly Confidential" and result["decision_source"] == "ml"


# --- risk: separate from classification ------------------------------------------------------

PAGES = [
    PageText(page_number=1, text="Contact sana@example.tn or amine@example.tn, phone +216 20 123 456."),
    PageText(page_number=2, text="Again: sana@example.tn. Signed copy attached."),
]


def test_risk_from_real_detection_is_deterministic_and_counts_distinct_values():
    findings = detect_pages(PAGES, [], 0.3, HMAC_KEY)
    first, second = assess(findings), assess(detect_pages(PAGES, [], 0.3, HMAC_KEY))
    assert first == second
    # The repeated address on page 2 adds nothing: same score as page 1 alone.
    assert first.score == assess(detect_pages(PAGES[:1], [], 0.3, HMAC_KEY)).score


def test_risk_does_not_change_when_only_the_label_changes(monkeypatch):
    findings = detect_pages(PAGES, [], 0.3, HMAC_KEY)
    text = "\n".join(p.text for p in PAGES)
    risks = []
    # Contact details make the rules raise the label to at least Internal, so Public is not reachable here.
    for label in ("Internal", "Confidential", "Highly Confidential"):
        fake_ml(monkeypatch, label, 0.95)
        assert predict_classification_v3_dict(text)["label"] == label
        risks.append(assess(findings))  # assess never receives the classification
    assert risks[0] == risks[1] == risks[2]


def test_highly_confidential_label_does_not_create_risk_on_its_own():
    # Classification says Highly Confidential; with no findings from the detection engine, risk stays 0.
    # (Secret detection rules are not wired into the engine yet: see docs/risk-contract.md.)
    assert predict_classification_v3_dict(AWS_KEY)["label"] == "Highly Confidential"
    assert assess(detect_pages([PageText(page_number=1, text=AWS_KEY)], [], 0.3, HMAC_KEY)).score == 0


# --- the report ------------------------------------------------------------------------------


def test_report_is_deterministic_and_honest():
    results = [evaluate("baseline-v1", MODELS["baseline-v1"], "realistic cases", *datasets()["realistic cases"], "ml")]
    report = render_report(results)
    assert report == render_report(results)
    assert "not production accuracy" in report
    assert "Confusion matrix" in report and "Precision" in report
