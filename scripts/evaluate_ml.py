"""Repeatable classifier evaluation and metrics report (SCRUM-46 M3).

    python -m scripts.evaluate_ml            # writes docs/ml-evaluation-report.md
    python -m scripts.evaluate_ml --stdout   # prints the report instead

Evaluates the committed models; it never trains or overwrites them. Two fictional test sets:
  * synthetic held-out test split (tests/fixtures/synthetic_dataset/test): same generator as training;
  * 40 hand-written "realistic" cases (scripts/evaluate_realistic.py): different wording from training.
For each model it reports ML only and the hybrid (ML + rules), with confusion matrix, per-class
precision/recall/F1 and dangerous under-classifications. Output is deterministic (no timestamps), so a
changed report in a PR means the behaviour changed.

These are numbers on small fictional data. They are NOT production accuracy.
"""

from __future__ import annotations

import argparse
import hashlib
from dataclasses import dataclass
from pathlib import Path

from sklearn.metrics import accuracy_score, confusion_matrix, precision_recall_fscore_support

from scripts.evaluate_realistic import CASES
from scripts.train_ml_classifier import load_dataset
from securewaste.core.ml_classifier import (
    LABEL_HIERARCHY,
    LABELS,
    MODEL_PATH,
    predict_classification_hybrid,
    predict_classification_with_confidence,
)

REPORT_PATH = Path("docs/ml-evaluation-report.md")
MODELS = {"baseline-v1": MODEL_PATH, "candidate-v3": MODEL_PATH.parent / "classifier_v3.pkl"}
RANK = {label.value: rank for label, rank in LABEL_HIERARCHY.items()}


@dataclass(frozen=True)
class Result:
    model: str
    dataset: str
    mode: str  # "ml" or "hybrid"
    y_true: list[str]
    y_pred: list[str]

    @property
    def accuracy(self) -> float:
        return accuracy_score(self.y_true, self.y_pred)

    @property
    def under(self) -> int:
        """Predicted LESS sensitive than the truth: the dangerous error for a DLP tool."""
        return sum(RANK[p] < RANK[t] for t, p in zip(self.y_true, self.y_pred, strict=True))

    @property
    def over(self) -> int:
        return sum(RANK[p] > RANK[t] for t, p in zip(self.y_true, self.y_pred, strict=True))


def datasets() -> dict[str, tuple[list[str], list[str]]]:
    texts, labels = load_dataset("test")
    return {
        "synthetic test split": (texts, labels),
        "realistic cases": ([text for _, text in CASES], [label for label, _ in CASES]),
    }


def evaluate(model: str, path: Path, dataset: str, texts: list[str], labels: list[str], mode: str) -> Result:
    if mode == "ml":
        pred = [predict_classification_with_confidence(t, path).label.value for t in texts]
    else:
        pred = [predict_classification_hybrid(t, path).value for t in texts]
    return Result(model, dataset, mode, list(labels), pred)


def evaluate_all() -> list[Result]:
    data = datasets()
    return [
        evaluate(model, path, name, texts, labels, mode)
        for model, path in MODELS.items()
        for name, (texts, labels) in data.items()
        for mode in ("ml", "hybrid")
    ]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def _detail(r: Result) -> list[str]:
    precision, recall, f1, support = precision_recall_fscore_support(r.y_true, r.y_pred, labels=LABELS, zero_division=0)
    matrix = confusion_matrix(r.y_true, r.y_pred, labels=LABELS)
    short = ["Pub", "Int", "Conf", "HConf"]
    lines = [
        f"#### {r.model} · {r.dataset} · {'hybrid (ML + rules)' if r.mode == 'hybrid' else 'ML only'}",
        "",
        f"Accuracy **{r.accuracy:.1%}** ({len(r.y_true)} documents) · "
        f"under-classified **{r.under}** · over-classified {r.over}",
        "",
        "| Class | Precision | Recall | F1 | Support |",
        "|---|---|---|---|---|",
    ]
    lines += [
        f"| {label} | {precision[i]:.2f} | {recall[i]:.2f} | {f1[i]:.2f} | {support[i]} |"
        for i, label in enumerate(LABELS)
    ]
    lines += ["", "Confusion matrix (rows = true, columns = predicted):", "", "| | " + " | ".join(short) + " |"]
    lines += ["|---" * (len(short) + 1) + "|"]
    lines += [f"| **{short[i]}** | " + " | ".join(str(v) for v in row) + " |" for i, row in enumerate(matrix)]
    return [*lines, ""]


def render_report(results: list[Result]) -> str:
    lines = [
        "# Classifier evaluation report (SCRUM-46 M3)",
        "",
        "Generated by `python -m scripts.evaluate_ml`. Do not edit by hand: re-run the command.",
        "",
        "> **These numbers come from small, fictional test sets. They are not production accuracy** and must not be",
        "> quoted as such. Classification (four sensitivity labels) is separate from document risk, which is",
        "> computed from findings by `core/risk.py` and is not evaluated here.",
        "",
        "## Models",
        "",
        "| Model | File | SHA-256 (first 16) |",
        "|---|---|---|",
    ]
    lines += [f"| {name} | `{path.name}` | `{_sha256(path)}` |" for name, path in MODELS.items()]
    lines += [
        "",
        "## Summary",
        "",
        "| Model | Test set | Mode | Accuracy | Under-classified | Over-classified |",
        "|---|---|---|---|---|---|",
    ]
    lines += [f"| {r.model} | {r.dataset} | {r.mode} | {r.accuracy:.1%} | {r.under} | {r.over} |" for r in results]
    lines += [
        "",
        "*Under-classified* = predicted less sensitive than the truth (the dangerous error: a secret could be",
        "shared as Public). *Over-classified* = more sensitive than the truth (costs reviewer time, not data).",
        "",
        "## Known limitations",
        "",
        "- **Tiny test sets.** 31 synthetic and 40 realistic documents: one error moves accuracy by 2.5–3 points.",
        "- **Synthetic split is optimistic.** It comes from the same generator and templates as the training data,",
        "  so it mainly measures how well the model learned the templates. The realistic cases are the more honest",
        "  number, and they are still short, clean, English-only, fictional sentences.",
        "- **baseline-v1** was trained on the synthetic train split only (`classifier_metadata.json`: 137 samples).",
        "- **candidate-v3 cannot be verified as leak-free.** Its report lists 226 training documents including 96",
        "  hand-written augmentation examples, but those examples and the v3 training script are not in the",
        "  repository. We cannot prove the test split or the realistic cases were kept out, so treat its higher",
        "  realistic score (97.5% vs 87.5%) as unconfirmed until it is retrained reproducibly from committed data.",
        "- **The realistic cases are not fully blind.** They have been seen while tuning the rules. A new blind set",
        "  is needed before any accuracy claim.",
        "- **Public over-classification.** Educational text about IBANs, passwords or encryption is pushed to a higher",
        "  label by the rules. This is the chosen trade-off (rules may raise, never lower, the label).",
        "- **No French/Arabic, OCR, tables or long multi-page documents** are evaluated.",
        "- Split hygiene is tested: no text appears in more than one of train/val/test",
        "  (`tests/unit/test_ml_regression.py`).",
        "",
        "## Details",
        "",
    ]
    for r in results:
        lines += _detail(r)
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--stdout", action="store_true", help="print the report instead of writing it")
    parser.add_argument("--output", type=Path, default=REPORT_PATH)
    args = parser.parse_args()
    report = render_report(evaluate_all())
    if args.stdout:
        print(report)
    else:
        args.output.write_text(report, encoding="utf-8")
        print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
